function makeFont(src, h, cap, space) {
  const glyphs = {};
  let x = 0;
  for (const ch in src) {
    const rows = src[ch];
    const w = Math.max(...rows.map((r) => r.length));
    glyphs[ch] = { rows, w, x };
    x += w + 1;
  }
  return { glyphs, h, cap, space, atlasW: x, atlases: new Map() };
}
export const MAIN = makeFont(MAIN_SRC, 9, 7, 1);
export const TINY = makeFont(TINY_SRC, 5, 5, 1);
// Lowercase falls back to uppercase in TINY.
function glyphOf(font, ch) {
  return font.glyphs[ch] || font.glyphs[ch.toUpperCase()] || font.glyphs[ch.toLowerCase()] || font.glyphs['?'];
}

function atlas(font, col) {
  let a = font.atlases.get(col);
  if (a) return a;
  a = canvas(font.atlasW, font.h);
  const C = rgb(col);
  const id = a.g.createImageData(font.atlasW, font.h), d = id.data;
  for (const ch in font.glyphs) {
    const gl = font.glyphs[ch];
    gl.rows.forEach((row, y) => {
      for (let i = 0; i < row.length; i++)
        if (row[i] === '#') {
          const k = (y * font.atlasW + gl.x + i) * 4;
          d[k] = C[0]; d[k + 1] = C[1]; d[k + 2] = C[2]; d[k + 3] = 255;
        }
    });
  }
  a.g.putImageData(id, 0, 0);
  font.atlases.set(col, a);
  return a;
}

export function textWidth(str, font = MAIN) {
  let w = 0;
  for (const ch of String(str)) w += glyphOf(font, ch).w + font.space;
  return Math.max(0, w - font.space);
}

function raw(g, str, x, y, col, font) {
  const a = atlas(font, col);
  for (const ch of str) {
    const gl = glyphOf(font, ch);
    g.drawImage(a, gl.x, 0, gl.w, font.h, x, y, gl.w, font.h);
    x += gl.w + font.space;
  }
}

// y = top of the capital letters. opts: align, outline (colour), shadow (colour), font, scale
export function text(g, str, x, y, col = '#fff6dc', opts = {}) {
  str = String(str);
  const font = opts.font || MAIN;
  const w = textWidth(str, font);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) raw(g, str, x, y + 1, opts.shadow, font);
  if (opts.outline) {
    const o = opts.outline;
    raw(g, str, x - 1, y, o, font); raw(g, str, x + 1, y, o, font);
    raw(g, str, x, y - 1, o, font); raw(g, str, x, y + 1, o, font);
    if (opts.thick) {
      raw(g, str, x - 1, y - 1, o, font); raw(g, str, x + 1, y - 1, o, font);
      raw(g, str, x - 1, y + 1, o, font); raw(g, str, x + 1, y + 1, o, font);
      raw(g, str, x, y + 2, o, font); raw(g, str, x - 1, y + 2, o, font); raw(g, str, x + 1, y + 2, o, font);
    }
  }
  raw(g, str, x, y, col, font);
  return w;
}

// Word-wrap into lines no wider than maxW.
export function wrap(str, maxW, font = MAIN) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t, font) > maxW && line) { out.push(line); line = word; }
      else line = t;
    }
    out.push(line);
  }
  return out;
}

// Large decorative text: renders MAIN at 2x into a sprite with gradient fill, outline and drop shadow.
const bigCache = new Map();
export function bigText(str, top, bottom, outline = '#26162b', shadow = '#26162b') {
  const key = str + top + bottom + outline;
  if (bigCache.has(key)) return bigCache.get(key);
  const w = textWidth(str) * 2, h = MAIN.h * 2;
  const m = canvas(w, h);
  m.g.scale(2, 2);
  raw(m.g, str, 0, 0, '#ffffff', MAIN);
  const c = canvas(w + 4, h + 5);
  // gradient fill (banded, pixel crisp)
  const f = canvas(w, h);
  for (let y = 0; y < h; y++) {
    const t = y / (MAIN.cap * 2);
    f.g.fillStyle = t < 0.45 ? top : t < 0.55 ? (y & 1 ? top : bottom) : bottom;
    f.g.fillRect(0, y, w, 1);
  }
  f.g.globalCompositeOperation = 'destination-in';
  f.g.drawImage(m, 0, 0);
  // highlight line along the top of each stroke
  const sil = (col) => { const s = canvas(w, h); s.g.drawImage(m, 0, 0); s.g.globalCompositeOperation = 'source-in'; s.g.fillStyle = col; s.g.fillRect(0, 0, w, h); return s; };
  const out = sil(outline), sh = sil(shadow);
  for (const [dx, dy] of [[0, 3], [1, 3], [2, 3], [0, 4], [1, 4], [2, 4]]) c.g.drawImage(sh, dx, dy);
  for (let dx = -2; dx <= 2; dx++) for (let dy = -2; dy <= 2; dy++) if (Math.abs(dx) + Math.abs(dy) <= 3) c.g.drawImage(out, 2 + dx, 2 + dy);
  c.g.drawImage(f, 2, 2);
  bigCache.set(key, c);
  return c;
}
