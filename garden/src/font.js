export const ADV = 6; // glyph advance
export const LINE = 10;
const cache = new Map();

function glyph(ch, color) {
  const key = color + ch;
  let c = cache.get(key);
  if (c) return c;
  const cols = G[ch] || G['?'];
  c = typeof OffscreenCanvas !== 'undefined' ? new OffscreenCanvas(5, 8) : Object.assign(document.createElement('canvas'), { width: 5, height: 8 });
  const x = c.getContext('2d');
  x.fillStyle = color;
  for (let i = 0; i < 5; i++) for (let b = 0; b < 8; b++) if (cols[i] & (1 << b)) x.fillRect(i, b, 1, 1);
  cache.set(key, c);
  return c;
}

export function width(str, scale = 1) { return (str.length * ADV - 1) * scale; }

// Draw text; opts: {scale, shadow, align:'left'|'center'|'right', max (px, ellipsis)}
export function text(ctx, str, x, y, color = '#fff', opts = {}) {
  const s = opts.scale || 1;
  str = String(str);
  if (opts.max) { while (str.length > 1 && width(str, s) > opts.max) str = str.slice(0, -2) + '…'; }
  const w = width(str, s);
  if (opts.align === 'center') x -= Math.round(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) {
    for (let i = 0; i < str.length; i++) ctx.drawImage(glyph(str[i], opts.shadow), x + i * ADV * s + s, y + s, 5 * s, 8 * s);
  }
  for (let i = 0; i < str.length; i++) ctx.drawImage(glyph(str[i], color), x + i * ADV * s, y, 5 * s, 8 * s);
  return w;
}

// Word-wrap into lines of at most maxW pixels.
export function wrap(str, maxW, scale = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (width(t, scale) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
